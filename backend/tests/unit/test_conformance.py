"""Tests for conformance document generation and verification (Task A).

Verifies that:
1. docs/CONFORMANCE.md and all docs/*.md / README.md contain zero absolute local paths.
2. Missing lock file produces R6 FAIL with 'dependencies not locked (F-012)'.
3. Missing metrics.json produces NOT-VERIFIED (never PASS).
4. Verdict line never says 'CONFORMANT' if any FAIL or NOT-VERIFIED exists.
5. docs/CONFORMANCE.md is generated by tools/check_conformance.py and is strictly in sync.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent.parent
DOCS_DIR = REPO_ROOT / "docs"
README_PATH = REPO_ROOT / "README.md"
CHECK_CONFORMANCE_SCRIPT = REPO_ROOT / "tools" / "check_conformance.py"


def test_no_absolute_paths_in_docs_or_readme() -> None:
    """Requirement 3: No absolute local path (file:///, E:\\, /home/, /Users/, etc.) in docs/*.md or README.md."""
    md_files = list(DOCS_DIR.glob("*.md"))
    if README_PATH.exists():
        md_files.append(README_PATH)

    # Patterns matching absolute paths on Windows or Unix
    forbidden_patterns = [
        (re.compile(r"file:///", re.IGNORECASE), "file:/// URL scheme"),
        (re.compile(r"\b[A-Za-z]:\\[a-zA-Z0-9_.-]+"), "Windows absolute path (e.g. C:\\ or E:\\)"),
        (re.compile(r"/home/[a-zA-Z0-9_.-]+"), "Unix /home/ path"),
        (re.compile(r"/Users/[a-zA-Z0-9_.-]+"), "macOS /Users/ path"),
    ]

    violations: list[str] = []
    for md_file in md_files:
        content = md_file.read_text(encoding="utf-8")
        for line_num, line in enumerate(content.splitlines(), start=1):
            for pat, desc in forbidden_patterns:
                if pat.search(line):
                    violations.append(
                        f"{md_file.relative_to(REPO_ROOT)}:{line_num} contains {desc}: {line.strip()}"
                    )

    assert not violations, f"Found {len(violations)} absolute local path violations:\n" + "\n".join(
        violations[:20]
    )


def test_conformance_r6_fails_when_lock_missing(tmp_path: Path) -> None:
    """Requirement 6: Lock file absent expects R6 FAIL with 'dependencies not locked (F-012)'."""
    sys.path.insert(0, str(REPO_ROOT / "tools"))
    from check_conformance import check_r6_reproducibility

    # Pass a temp directory where uv.lock definitely does not exist
    status, reason = check_r6_reproducibility(repo_root=tmp_path)
    assert status == "FAIL"
    assert "dependencies not locked (F-012)" in reason


def test_conformance_r2_r4_not_verified_when_metrics_missing(tmp_path: Path) -> None:
    """Requirement 6: Missing metrics.json produces NOT-VERIFIED, not PASS."""
    sys.path.insert(0, str(REPO_ROOT / "tools"))
    from check_conformance import check_r2_no_leakage, check_r4_evaluation_validity

    status_r2, reason_r2 = check_r2_no_leakage(repo_root=tmp_path)
    assert status_r2 == "NOT-VERIFIED"
    assert "missing" in reason_r2.lower()

    status_r4, reason_r4 = check_r4_evaluation_validity(repo_root=tmp_path)
    assert status_r4 == "NOT-VERIFIED"
    assert "missing" in reason_r4.lower()


def test_conformance_verdict_logic() -> None:
    """Requirement 4: Verdict line must never say 'CONFORMANT' unless FAIL and NOT-VERIFIED are both zero."""
    sys.path.insert(0, str(REPO_ROOT / "tools"))
    from check_conformance import compute_verdict

    # Case 1: Has FAIL -> NON-CONFORMANT
    v1 = compute_verdict({"PASS": 10, "FAIL": 1, "NOT-VERIFIED": 0, "PENDING": 1, "MANUAL": 2})
    assert "CONFORMANT" in v1
    assert "NON-CONFORMANT" in v1 or "NOT FULLY CONFORMANT" in v1
    assert "Verdict: CONFORMANT." not in v1

    # Case 2: Has NOT-VERIFIED -> NOT FULLY CONFORMANT / PENDING VERIFICATION
    v2 = compute_verdict({"PASS": 10, "FAIL": 0, "NOT-VERIFIED": 1, "PENDING": 1, "MANUAL": 2})
    assert "Verdict: CONFORMANT." not in v2

    # Case 3: Zero FAIL and Zero NOT-VERIFIED -> CONFORMANT
    v3 = compute_verdict({"PASS": 10, "FAIL": 0, "NOT-VERIFIED": 0, "PENDING": 1, "MANUAL": 2})
    assert "CONFORMANT" in v3
    assert "NON-CONFORMANT" not in v3


def test_conformance_up_to_date() -> None:
    """Requirement 5: committed docs/CONFORMANCE.md must match in-memory regeneration."""
    assert CHECK_CONFORMANCE_SCRIPT.exists(), f"Missing {CHECK_CONFORMANCE_SCRIPT}"

    result = subprocess.run(
        [sys.executable, str(CHECK_CONFORMANCE_SCRIPT), "--check"],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, (
        f"Conformance document is out of date or failed check:\n{result.stderr}\n{result.stdout}"
    )
