#!/usr/bin/env python3
"""Generate or verify docs/VENDORED_FILES.md manifest for backend/discovery/."""

import argparse
import hashlib
import sys
from pathlib import Path


def compute_sha256(filepath: Path) -> str:
    """Compute sha256 checksum of a file after replacing b'\\r\\n' with b'\\n'."""
    raw = filepath.read_bytes()
    normalized = raw.replace(b"\r\n", b"\n")
    return hashlib.sha256(normalized).hexdigest()


def generate_manifest(repo_root: Path) -> str:
    """Generate markdown manifest content for vendored files."""
    discovery_dir = repo_root / "backend" / "discovery"
    if not discovery_dir.exists():
        raise FileNotFoundError(f"Discovery directory not found: {discovery_dir}")

    files = []
    for p in discovery_dir.rglob("*"):
        if p.is_file() and "__pycache__" not in p.parts and not p.name.endswith(".pyc"):
            files.append(p)

    files.sort(key=lambda p: p.relative_to(repo_root).as_posix())

    lines = [
        "# Vendored Files Manifest",
        "",
        "> Auto-generated by `python tools/vendored_manifest.py`. Do not edit by hand.",
        "> Source: Recommenders 1.2.1 (MIT License, https://github.com/recommenders-team/recommenders)",
        "",
        "| Path | Size (bytes) | SHA-256 | Origin Path |",
        "|---|---|---|---|",
    ]

    for p in files:
        rel_repo = p.relative_to(repo_root).as_posix()
        rel_discovery = p.relative_to(discovery_dir).as_posix()
        normalized_content = p.read_bytes().replace(b"\r\n", b"\n")
        size = len(normalized_content)
        sha256 = hashlib.sha256(normalized_content).hexdigest()

        if rel_discovery == "LICENSE":
            origin_path = "LICENSE"
        elif rel_discovery == "NOTICE.md":
            origin_path = "[Original notice added for Discovery Engine]"
        else:
            origin_path = f"recommenders/{rel_discovery}"

        lines.append(
            f"| `{rel_repo}` | {size} | `{sha256[:16]}...` | `{origin_path}` |"
        )

    lines.append("")
    lines.append(f"*Total vendored files: {len(files)}*")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate or verify vendored files manifest"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that committed manifest matches disk",
    )
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parent.parent
    manifest_path = repo_root / "docs" / "VENDORED_FILES.md"

    generated = generate_manifest(repo_root)

    if args.check:
        if not manifest_path.exists():
            print(f"Error: {manifest_path} does not exist", file=sys.stderr)
            sys.exit(1)
        current = manifest_path.read_text(encoding="utf-8")
        if current.strip() != generated.strip():
            print(
                "Error: docs/VENDORED_FILES.md is out of date. Run 'python tools/vendored_manifest.py'",
                file=sys.stderr,
            )
            sys.exit(1)
        print("Manifest check passed: docs/VENDORED_FILES.md is up to date.")
    else:
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_text(generated, encoding="utf-8")
        print(f"Manifest written to {manifest_path}")


if __name__ == "__main__":
    main()
